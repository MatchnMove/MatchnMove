import assert from "node:assert/strict";
import test from "node:test";
import { randomUUID } from "node:crypto";
import { prisma } from "../lib/db";
import { emailStationCompanies, emailStationCompany } from "../lib/email-station";
import { locked } from "../lib/recruitment";
import { manageCampaign } from "../lib/mover-outreach-campaigns";

const database = process.env.EMAIL_STATION_TEST_DATABASE_URL;
test("Email station derives real company progress, scopes records and paginates without exposing email bodies", { skip: !database, timeout: 120000 }, async t => {
  const url = new URL(database!);
  assert.ok(["localhost", "127.0.0.1"].includes(url.hostname));
  assert.ok(url.pathname.endsWith("_test"));
  assert.equal(process.env.DATABASE_URL, database);
  const tag = randomUUID();
  const user = await prisma.user.create({ data: { email: `station-${tag}@validation.invalid`, passwordHash: "unused", role: "ADMIN", adminRole: "RECRUITMENT_ADMIN", name: "Station colleague" } });
  const other = await prisma.user.create({ data: { email: `other-${tag}@validation.invalid`, passwordHash: "unused", role: "ADMIN", adminRole: "RECRUITMENT_ADMIN", name: "Other colleague" } });
  const actor = { id: user.id, role: "RECRUITMENT_ADMIN" as const, canSend: false, canViewLeads: false };
  const owner = { ...actor, role: "OWNER" as const, canViewLeads: true };
  const now = new Date(), past = new Date(now.getTime() - 86400000), future = new Date(now.getTime() + 86400000);
  let sequence = 0;
  const makeCompany = (name: string, extra = {}) => prisma.moverProspect.create({ data: { companyName: `${name} ${tag}`, normalizedName: `${name}-${tag}`, email: `company-${++sequence}-${tag}@validation.invalid`, contactName: `Contact ${name}`, assignedAdminId: user.id, serviceAreas: [], serviceTypes: [], consentBasis: "EXPRESS", consentEvidence: "Local fixture only", ...extra } });
  const makeCampaign = (prospectId: string, status = "ACTIVE", extra = {}) => prisma.outreachCampaign.create({ data: { prospectId, createdById: user.id, status, initialSentAt: past, nextDueAt: future, revisitAt: new Date(now.getTime() + 90 * 86400000), ...extra } });
  const makeMessage = (prospectId: string, campaignId: string | null, stage = 0, status = "SENT", extra = {}) => prisma.outreachMessage.create({ data: { prospectId, campaignId, adminId: user.id, sequence: stage, status, subject: "Company invitation", introduction: "PRIVATE_BODY_NEVER_LISTED", text: "PRIVATE_BODY_NEVER_LISTED", html: "<p>PRIVATE_BODY_NEVER_LISTED</p>", attributionHash: randomUUID(), unsubscribeHash: randomUUID(), attributionExpiresAt: future, sentAt: status === "SENT" ? past : null, ...extra } });
  t.after(() => prisma.$disconnect());
  const active = await makeCompany("Active Movers");
  const activeCampaign = await makeCampaign(active.id);
  await makeMessage(active.id, activeCampaign.id);
  await makeMessage(active.id, activeCampaign.id, 1, "DRAFT", { templateKey: "MOVER_FOLLOWUP_1" });
  const response = await makeCompany("Replied Movers", { respondedAt: past, status: "INTERESTED" });
  await makeCampaign(response.id, "STOPPED");
  const revisit = await makeCompany("Review Cleaners", { businessType: "CLEANING" });
  const reviewCampaign = await makeCampaign(revisit.id, "ACTIVE", { revisitAt: past, nextDueAt: null });
  await makeMessage(revisit.id, reviewCampaign.id, 0, "SENT", { templateKey: "CLEANER_GENERAL" });
  const paused = await makeCompany("Paused Movers");
  await makeCampaign(paused.id, "PAUSED");
  const registered = await makeCompany("Registered Cleaners", { businessType: "CLEANING", registeredAt: past, status: "REGISTERED", respondedAt: past });
  await makeCampaign(registered.id, "STOPPED");
  const legacy = await makeCompany("Previous Movers");
  await makeMessage(legacy.id, null);
  const uncertain = await makeCompany("Uncertain Movers");
  await makeMessage(uncertain.id, null, 0, "NEEDS_REVIEW");
  await makeCompany("Percent % Cleaners", { businessType: "CLEANING" });
  const removed = await makeCompany("Removed Movers", { removedAt: past });
  const outside = await makeCompany("Outside Movers", { assignedAdminId: other.id });

  await t.test("metrics and status filters agree, including due reviews and stopped responses", async () => {
    const result = await emailStationCompanies(actor, {});
    assert.equal(result.metrics.companies, 8);
    assert.equal(result.metrics.inProgress, 1);
    assert.equal(result.metrics.responses, 1);
    assert.equal(result.metrics.revisitDue, 1);
    assert.equal(result.count, 8);
    assert.equal(result.items.find(item => item.id === active.id)?.status, "IN_PROGRESS");
    assert.equal(result.items.find(item => item.id === active.id)?.sentCount, 1);
    assert.equal(result.items.find(item => item.id === response.id)?.status, "RESPONSE_RECEIVED");
    assert.equal(result.items.find(item => item.id === registered.id)?.status, "REGISTERED");
    assert.equal(result.items.find(item => item.id === legacy.id)?.status, "LEGACY");
    assert.equal(result.items.find(item => item.id === uncertain.id)?.status, "NEEDS_REVIEW");
    assert.equal(result.items.find(item => item.id === paused.id)?.status, "PAUSED");
    assert.equal((await emailStationCompanies(actor, { status: "REVISIT_DUE" })).items[0]?.id, revisit.id);
    assert.equal((await emailStationCompanies(actor, { status: "RESPONSE_RECEIVED" })).count, 1);
    assert.equal((await emailStationCompanies(actor, { status: "IN_PROGRESS" })).count, 1);
    assert.doesNotMatch(JSON.stringify(result), /PRIVATE_BODY_NEVER_LISTED|attributionHash|unsubscribeHash/);
  });
  await t.test("company ownership, removal and literal search are enforced before pagination", async () => {
    assert.equal((await emailStationCompanies(owner, {})).count, 9);
    assert.equal((await emailStationCompanies(actor, { q: "Outside" })).count, 0);
    assert.equal((await emailStationCompanies(actor, { q: "Removed" })).count, 0);
    await assert.rejects(emailStationCompany(actor, outside.id), /Company not found/);
    await assert.rejects(emailStationCompany(actor, removed.id), /Company not found/);
    assert.equal((await emailStationCompanies(actor, { q: "Contact Active" })).count, 1);
    assert.equal((await emailStationCompanies(actor, { q: "%" })).count, 1);
    assert.equal((await emailStationCompanies(actor, { q: "' OR true --" })).count, 0);
    const cleaners = await emailStationCompanies(actor, { businessType: "CLEANING" });
    assert.equal(cleaners.count, 3);
    assert.ok(cleaners.items.every(item => item.businessType === "CLEANING"));
  });
  await t.test("latest campaign controls progress and detail is metadata only", async () => {
    await makeCampaign(active.id, "CLOSED", { createdAt: new Date(now.getTime() - 10 * 86400000), nextDueAt: null });
    const detail = await emailStationCompany(actor, active.id);
    assert.equal(detail.campaign?.id, activeCampaign.id);
    assert.equal(detail.company.status, "IN_PROGRESS");
    assert.equal(detail.messages.filter(item => item.status === "SENT").length, 1);
    assert.equal(detail.company.nextDueAt?.toISOString(), future.toISOString());
    assert.equal(detail.templates.length, 6);
    assert.ok(detail.templates.every(template => template.key.startsWith("MOVER_")));
    assert.doesNotMatch(JSON.stringify(detail), /PRIVATE_BODY_NEVER_LISTED|attributionHash|unsubscribeHash/);
    const cleaning = await emailStationCompany(actor, revisit.id);
    assert.ok(cleaning.templates.every(template => template.key.startsWith("CLEANER_")));
    const quote = await prisma.quoteRequest.create({ data: { name: "Private fixture", email: "private@validation.invalid", phone: "0219999999", fromAddress: "21 Private Street", toAddress: "9 Private Lane", fromCity: "Auckland", toCity: "Hamilton", fromRegion: "Auckland", toRegion: "Waikato", fromPostcode: "1010", toPostcode: "3200", fromCountry: "NZ", toCountry: "NZ", fromPropertyType: "House", toPropertyType: "House", bedrooms: "3" } });
    const restricted = await makeMessage(active.id, null, 0, "SENT", { quoteRequestId: quote.id, subject: "PRIVATE_LEAD_SUBJECT" });
    const colleagueView = await emailStationCompany(actor, active.id);
    assert.equal(colleagueView.messages.find(item => item.id === restricted.id)?.canPreview, false);
    assert.doesNotMatch(JSON.stringify(colleagueView), /PRIVATE_LEAD_SUBJECT|21 Private Street|private@validation.invalid/);
    assert.equal((await emailStationCompany(owner, active.id)).messages.find(item => item.id === restricted.id)?.canPreview, true);
  });
  await t.test("company pages retain an exact total beyond one page", async () => {
    for (let i = 0; i < 27; i++) await makeCompany(`Paged ${String(i).padStart(2, "0")}`);
    const first = await emailStationCompanies(actor, { q: "Paged", page: 1 });
    const second = await emailStationCompanies(actor, { q: "Paged", page: 2 });
    assert.equal(first.count, 27); assert.equal(second.count, 27);
    assert.equal(first.items.length, 25); assert.equal(second.items.length, 2);
    assert.equal(new Set([...first.items, ...second.items].map(item => item.id)).size, 27);
    assert.equal(await prisma.emailDelivery.count(), 0);
  });
  await t.test("a due manual review can be previewed before the worker runs, without sending", async () => {
    const draft = await locked(tx => manageCampaign(tx, actor, { campaignId: reviewCampaign.id, updatedAt: reviewCampaign.updatedAt.toISOString(), operation: "reengage" }));
    assert.ok("templateKey" in draft);
    assert.equal(draft.templateKey, "CLEANER_REENGAGEMENT");
    assert.equal(draft.status, "DRAFT");
    assert.equal((await prisma.outreachCampaign.findUniqueOrThrow({ where: { id: reviewCampaign.id } })).status, "REVIEW_DUE");
    assert.equal(await prisma.emailDelivery.count(), 0);
  });
});
